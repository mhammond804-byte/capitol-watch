// Helper: fetch from Congress.gov API v3
function congressFetch(urlPath) {
  return new Promise((resolve, reject) => {
    const separator = urlPath.includes('?') ? '&' : '?';
    const url = `${BASE_URL}${urlPath}${separator}format=json`;
    https.get(url, { headers: { 'X-Api-Key': API_KEY } }, (res) => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        if (res.statusCode >= 400) {
          console.error(`Congress.gov API error ${res.statusCode} for ${urlPath}: ${data.substring(0, 200)}`);
          resolve(null);
          return;
        }
        try { resolve(JSON.parse(data)); }
        catch(e) {
          console.error(`Parse error for ${urlPath}: ${data.substring(0, 200)}`);
          resolve(null);
        }
      });
    }).on('error', (e) => {
      console.error(`Network error for ${urlPath}:`, e.message);
      resolve(null);
    });
  });
}

