// GET /api/zip/:zip — Look up state by zip code (uses zippopotam.us, free, no key)
app.get('/api/zip/:zip', zipLimiter, (req, res) => {
  const zip = req.params.zip.replace(/\D/g, '').substring(0, 5);
  if (zip.length !== 5) return res.status(400).json({ error: 'Please enter a valid 5-digit zip code' });
  https.get(`https://api.zippopotam.us/us/${zip}`, (r) => {
    let data = '';
    r.on('data', chunk => data += chunk);
    r.on('end', () => {
      try {
        if (r.statusCode === 404) return res.status(404).json({ error: 'Zip code not found — try your state dropdown instead' });
        const d = JSON.parse(data);
        const stateCode = d.places?.[0]?.['state abbreviation'];
        const city = d.places?.[0]?.['place name'] || '';
        if (!stateCode) return res.status(404).json({ error: 'Could not find state for that zip code' });
        res.json({ stateCode, city });
      } catch(e) {
        res.status(500).json({ error: 'Could not look up zip code' });
      }
    });
  }).on('error', () => res.status(500).json({ error: 'Zip lookup failed — please try again' }));
});

