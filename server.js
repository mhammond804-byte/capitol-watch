// POST /api/vote — Submit a vote (approve/disapprove) on a bill
app.post('/api/vote', voteLimiter, (req, res) => {
  const { billId, vote, voter, email } = req.body;
  if (!billId || !vote || !['approve', 'disapprove'].includes(vote)) {
    return res.status(400).json({ error: 'Missing billId or invalid vote (use "approve" or "disapprove")' });
  }
  if (!voter || !voter.trim()) {
    return res.status(400).json({ error: 'Voter name/identifier is required' });
  }
  if (!votesCache[billId]) {
    votesCache[billId] = { approve: 0, disapprove: 0, voters: {} };
  }
  // If this voter already voted on this bill, reject
  if (votesCache[billId].voters[voter.trim()]) {
    return res.status(400).json({ error: `${voter.trim()} has already voted on this bill` });
  }
  votesCache[billId][vote]++;
  votesCache[billId].voters[voter.trim()] = { vote, email: email || '' };
  saveVotes();
  res.json({ billId, ...votesCache[billId], total: votesCache[billId].approve + votesCache[billId].disapprove });
});

// GET /api/votes — Get vote tallies for all bills (for public display)
// NOTE: Only returns counts — voter names/emails are saved to votes.json
