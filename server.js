// GET /api/national/stats — Aggregate stats for national view
app.get('/api/national/stats', apiLimiter, async (req, res) => {
  try {
    const data = await congressFetch('/bill/119?limit=250&offset=0');
    const bills = data?.bills || [];
    const total = bills.length;
    let byParty = { D: 0, R: 0, I: 0, other: 0 };
    let byStatus = { Introduced: 0, 'Passed House': 0, 'Passed Senate': 0, Enacted: 0, Vetoed: 0, Other: 0 };
    let topics = {};

    bills.forEach(b => {
      // By status
      const status = (b.latestAction?.text || '').toLowerCase();
      if (status.includes('enacted') || status.includes('became law') || status.includes('signed')) byStatus.Enacted++;
      else if (status.includes('veto')) byStatus.Vetoed++;
      else if (b.originChamber === 'House' && (status.includes('passed') || status.includes('agreed'))) byStatus['Passed House']++;
      else if (b.originChamber === 'Senate' && (status.includes('passed') || status.includes('agreed'))) byStatus['Passed Senate']++;
      else if (status.includes('introduced') || !b.latestAction) byStatus.Introduced++;
      else byStatus.Other++;

      // By topic (from subjects)
      if (b.subjects?.subject) {
        (Array.isArray(b.subjects.subject) ? b.subjects.subject : [b.subjects.subject]).forEach(s => {
          const term = (s.term || '').trim();
          if (term) topics[term] = (topics[term] || 0) + 1;
        });
      }
    });

    // Sort topics by count
    const hotTopics = Object.entries(topics)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 15)
      .map(([term, count]) => ({ term, count }));

    res.json({ total, byParty, byStatus, hotTopics });
  } catch (e) {
    console.error('Error fetching national stats:', e.message);
    res.json({ total: 0, byParty: {}, byStatus: {}, hotTopics: [] });
  }
});

