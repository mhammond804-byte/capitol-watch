// GET /api/bills/search?q=keyword — Search bills by keyword (client-side filter on fetched bills)
app.get('/api/bills/search', apiLimiter, async (req, res) => {
  const q = req.query.q;
  if (!q || q.trim() === '') {
    return res.json({ bills: [] });
  }
  const keyword = q.trim().toLowerCase();
  try {
    const data = await congressFetch(`/bill/119?limit=250&offset=0`);
    const bills = (data?.bills || []).filter(b => {
      const title = (b.title || '').toLowerCase();
      const action = (b.latestAction?.text || '').toLowerCase();
      const type = (b.type || '').toLowerCase();
      const number = String(b.number || '');
      return title.includes(keyword) || action.includes(keyword) || 
             `${type} ${number}`.includes(keyword);
    });
    res.json({ bills });
  } catch (e) {
    console.error('Error searching bills:', e.message);
    res.json({ bills: [] });
  }
});

